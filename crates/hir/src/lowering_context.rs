impl Context {
    /// Returns the expression at the given index
    pub fn expr(&self, idx: Idx<Expr>) -> &Expr {
        &self.database.exprs[idx]
    }

    /// Returns a mutable expression at the given index
    pub fn expr_mut(&mut self, idx: Idx<Expr>) -> &mut Expr {
        &mut self.database.exprs[idx]
    }

    /// Returns the type expression at the given index
    pub fn type_expr(&self, idx: Idx<TypeExpr>) -> &TypeExpr {
        &self.database.type_exprs[idx]
    }

    /// Gets an interned key by its string
    //
    // TODO: keep this public? or offer more specific getters only
    pub fn lookup(&self, key: Key) -> &str {
        self.interner.lookup(key)
    }

    /// Gets a reference to the type for an expression
    pub fn expr_type(&self, idx: Idx<Expr>) -> &Type {
        self.type_database.type_(self.expr_type_idx(idx))
    }

    /// Gets the index of a type for an expression
    pub fn expr_type_idx(&self, idx: Idx<Expr>) -> Idx<Type> {
        self.type_database.get_expr_type(idx)
    }

    /// Instantiates a HIR type by substituting type parameters
    pub fn instantiate_type(
        &mut self,
        ty: Idx<Type>,
        substitutions: &[(TypeSymbol, Idx<Type>)],
    ) -> Idx<Type> {
        let substitutions: HashMap<TypeSymbol, Idx<Type>> = substitutions.iter().copied().collect();
        substitute_type(ty, &substitutions, self)
    }

    /// Builds expression types for lowering one monomorphized function body
    pub fn instantiate_expr_types(
        &mut self,
        substitutions: &[(TypeSymbol, Idx<Type>)],
    ) -> HashMap<Idx<Expr>, Idx<Type>> {
        let substitutions: HashMap<TypeSymbol, Idx<Type>> = substitutions.iter().copied().collect();
        self.type_database
            .iter_expr_types()
            .collect_vec()
            .into_iter()
            .map(|(expr, ty)| (expr, substitute_type(ty, &substitutions, self)))
            .collect()
    }

    /// Builds value-symbol type overrides for a monomorphized function body.
    pub fn instantiate_value_types(
        &mut self,
        substitutions: &[(TypeSymbol, Idx<Type>)],
    ) -> HashMap<ValueSymbol, Idx<Type>> {
        let substitutions: HashMap<TypeSymbol, Idx<Type>> = substitutions.iter().copied().collect();
        self.type_database
            .iter_value_types()
            .collect_vec()
            .into_iter()
            .map(|(symbol, ty)| (symbol, substitute_type(ty, &substitutions, self)))
            .collect()
    }

    /// Builds generic-argument overrides for calls inside a monomorphized
    /// function body.
    pub fn instantiate_call_type_args(
        &mut self,
        substitutions: &[(TypeSymbol, Idx<Type>)],
    ) -> HashMap<Idx<Expr>, Box<[Idx<Type>]>> {
        let substitutions: HashMap<TypeSymbol, Idx<Type>> = substitutions.iter().copied().collect();
        let calls = self
            .database
            .exprs
            .iter()
            .filter_map(|(idx, expr)| match expr {
                Expr::Call(call) if !call.type_args.is_empty() => {
                    Some((idx, call.type_args.clone()))
                }
                _ => None,
            })
            .collect_vec();
        calls
            .into_iter()
            .map(|(idx, type_args)| {
                let type_args = type_args
                    .iter()
                    .map(|ty| substitute_type(*ty, &substitutions, self))
                    .collect_vec()
                    .into_boxed_slice();
                (idx, type_args)
            })
            .collect()
    }

    pub fn type_(&self, idx: Idx<Type>) -> &Type {
        self.type_database.type_(idx)
    }

    pub fn type_mut(&mut self, idx: Idx<Type>) -> &mut Type {
        self.type_database.type_mut(idx)
    }

    pub fn type_is_function(&self, idx: Idx<Type>) -> bool {
        matches!(self.type_(idx), Type::Function(_))
    }

    pub fn type_of_value(&self, value: &ValueSymbol) -> &Type {
        self.type_database.type_(self.type_idx_of_value(value))
    }

    pub fn type_idx_of_value(&self, value: &ValueSymbol) -> Idx<Type> {
        self.type_database.get_type_from_valuesymbol(value)
    }

    pub fn range_of_expr(&self, idx: Idx<Expr>) -> TextRange {
        self.database.expr_ranges[idx]
    }

    pub fn type_of_type_expr(&self, idx: Idx<TypeExpr>) -> Idx<Type> {
        self.type_database.get_type_expr_type(idx)
    }

    pub fn range_of_type_expr(&self, idx: Idx<TypeExpr>) -> TextRange {
        self.database.type_expr_ranges[idx]
    }

    pub fn value_definition_range(&self, symbol: ValueSymbol) -> Option<TextRange> {
        self.database.value_definition_ranges.get(&symbol).copied()
    }

    pub fn type_definition_range(&self, symbol: TypeSymbol) -> Option<TextRange> {
        self.database.type_definition_ranges.get(&symbol).copied()
    }

    pub fn builtin_id(&self, symbol: ValueSymbol) -> Option<BuiltinId> {
        self.database.value_builtins.get(&symbol).copied()
    }

    fn find_local(&mut self, name: &str) -> Option<ValueSymbol> {
        let key = self.interner.intern(name);

        self.find_value(key)
    }

    /// Gets the interned Key for a value symbol
    pub fn value_symbol_key(&self, symbol: ValueSymbol) -> Key {
        self.database.value_names[&symbol]
    }

    /// Gets the interned string for a value symbol
    pub fn value_symbol_str(&self, symbol: ValueSymbol) -> &str {
        let key = self.database.value_names[&symbol];
        self.lookup(key)
    }

    /// Gets the interned Key for a type symbol
    pub fn type_symbol_key(&self, symbol: TypeSymbol) -> Key {
        self.database.type_names[&symbol]
    }

    /// Gets the interned string for a type symbol
    pub fn type_symbol_str(&self, symbol: TypeSymbol) -> &str {
        let key = self.database.type_names[&symbol];
        self.lookup(key)
    }

    pub fn pattern(&self, idx: Idx<Pattern>) -> &Pattern {
        &self.database.patterns[idx]
    }

    pub fn pattern_mut(&mut self, idx: Idx<Pattern>) -> &mut Pattern {
        &mut self.database.patterns[idx]
    }

    pub fn lookup_operator(&self, symbol: ValueSymbol) -> Option<IntrinsicExpr> {
        self.database.lookup_operator(symbol)
    }

    pub fn core_types(&self) -> &CoreTypes {
        &self.type_database.core
    }

    pub fn mutability_of(&self, symbol: &ValueSymbol) -> Mutability {
        *self
            .database
            .mutabilities
            .get(symbol)
            .expect("symbol to exist")
    }
}

impl Context {
    pub fn find_value(&self, name: Key) -> Option<ValueSymbol> {
        self.current_scopes()
            .find_value(name)
            .or_else(|| self.find_prelude_value(name))
            .or_else(|| self.core_scopes().find_value(name))
    }

    fn find_prelude_value(&self, name: Key) -> Option<ValueSymbol> {
        self.stdlib_prelude
            .filter(|prelude| *prelude != self.current_module_id)
            .and_then(|prelude| self.module_tree.get(prelude))
            .and_then(|prelude| prelude.exports.values.get(&name).copied())
    }

    fn find_type(&self, name: Key) -> Option<TypeSymbol> {
        self.current_scopes()
            .find_type(name)
            .or_else(|| self.find_prelude_type(name))
            .or_else(|| self.core_scopes().find_type(name))
    }

    fn find_prelude_type(&self, name: Key) -> Option<TypeSymbol> {
        self.stdlib_prelude
            .filter(|prelude| *prelude != self.current_module_id)
            .and_then(|prelude| self.module_tree.get(prelude))
            .and_then(|prelude| prelude.exports.types.get(&name).copied())
    }

    /// Resolves a direct child module name without applying import rules.
    pub fn child_module(&self, parent: ModuleId, name: Key) -> Option<ModuleId> {
        self.module_tree.child(parent, name)
    }

    pub fn find_module_alias(&self, name: Key) -> Option<ModuleId> {
        self.current_scopes().find_module(name).or_else(|| {
            self.stdlib_prelude
                .filter(|prelude| *prelude != self.current_module_id)
                .and_then(|prelude| self.module_tree.get(prelude))
                .and_then(|prelude| prelude.exports.modules.get(&name).copied())
        })
    }

    fn resolve_module_path_strings(&mut self, path: &[String]) -> Option<ModuleId> {
        let keys = path
            .iter()
            .map(|segment| self.interner.intern(segment))
            .collect_vec();
        self.module_tree.resolve_path(ModuleId::BOOTSTRAP, &keys)
    }

    fn resolve_imported_value(
        &mut self,
        module_path: &[String],
        symbol_name: Option<String>,
    ) -> Option<ValueSymbol> {
        let symbol_name = symbol_name?;
        let module = self.resolve_module_path_strings(module_path)?;
        let symbol_key = self.interner.intern(&symbol_name);
        self.module_tree
            .get(module)?
            .exports
            .values
            .get(&symbol_key)
            .copied()
    }

    fn resolve_imported_type(
        &mut self,
        module_path: &[String],
        symbol_name: Option<String>,
    ) -> Option<TypeSymbol> {
        let symbol_name = symbol_name?;
        let module = self.resolve_module_path_strings(module_path)?;
        let symbol_key = self.interner.intern(&symbol_name);
        self.module_tree
            .get(module)?
            .exports
            .types
            .get(&symbol_key)
            .copied()
    }

    /// Resolves a module path by walking child namespaces from `from`.
    pub fn resolve_module_path(&self, from: ModuleId, path: &[Key]) -> Option<ModuleId> {
        path.iter().try_fold(from, |module, segment| {
            self.module_tree.child(module, *segment)
        })
    }

    pub fn exported_value(&self, module: ModuleId, name: Key) -> Option<ValueSymbol> {
        self.module(module)
            .and_then(|module| module.exports.values.get(&name).copied())
    }

    pub fn exported_type(&self, module: ModuleId, name: Key) -> Option<TypeSymbol> {
        self.module(module)
            .and_then(|module| module.exports.types.get(&name).copied())
    }

    pub fn find_symbol_of_expr(&self, expr: Idx<Expr>) -> Option<ValueSymbol> {
        match self.expr(expr) {
            Expr::VarRef(var_ref_expr) => Some(var_ref_expr.symbol),
            _ => None,
        }
    }

    fn current_scopes(&self) -> &ModuleScopes {
        self.module_tree.scope(self.current_module_id)
    }

    fn core_scopes(&self) -> &ModuleScopes {
        self.module_tree.scope(CORE_MODULE_ID)
    }

    fn current_scopes_mut(&mut self) -> &mut ModuleScopes {
        self.module_tree.scope_mut(self.current_module_id)
    }
}

